/**
 * Copies contract ABIs from forge output into `packages/shared/src/abis/` as `<Name>.json` plus a
 * generated `index.ts` exporting each as an `as const` literal, so viem infers function and error types.
 *
 *   (cd contracts && forge build) && pnpm abi:sync
 *
 * Names listed in CONTRACTS but not yet built are skipped with a note.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const OUT = `${ROOT}contracts/out`;
const DEST = `${ROOT}packages/shared/src/abis`;

/** Later tasks append names here (e.g. CreditFacility, RepaymentRouter). */
const CONTRACTS = [
  "KYARegistry",
  "ReceivableRegistry",
  "ReceivableCreditNote",
  "CreditFacility",
  "RepaymentRouter",
  "CashEthSwapVMRouter",
  "CashEthOrderBuilder",
  "TestStablecoin",
  "CashEthTaker",
  // From the aqua submodule (lib/aqua/contracts/AquaRouter.sol), compiled into the same out/ tree.
  "AquaRouter",
] as const;

mkdirSync(DEST, { recursive: true });
const synced: string[] = [];
for (const name of CONTRACTS) {
  const artifact = `${OUT}/${name}.sol/${name}.json`;
  if (!existsSync(artifact)) {
    console.log(`skip ${name}: ${artifact} not built`);
    continue;
  }
  const { abi } = JSON.parse(readFileSync(artifact, "utf8")) as { abi: unknown[] };
  writeFileSync(`${DEST}/${name}.json`, `${JSON.stringify(abi, null, 2)}\n`);
  synced.push(name);
  console.log(`synced ${name} (${abi.length} entries)`);
}
if (synced.length === 0) throw new Error("No ABIs synced: run `forge build` in contracts/ first.");

const index = [
  "// Generated by scripts/abi-sync.ts from contracts/out. Do not edit by hand.",
  ...synced.map(
    (name) =>
      `export const ${name}Abi = ${JSON.stringify(
        JSON.parse(readFileSync(`${DEST}/${name}.json`, "utf8")),
        null,
        2,
      )} as const;`,
  ),
  "",
].join("\n\n");
writeFileSync(`${DEST}/index.ts`, index);
console.log(`wrote ${DEST}/index.ts`);
