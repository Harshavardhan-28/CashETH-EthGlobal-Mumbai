/**
 * Creates the ten CashETH demo accounts on Hedera testnet, associates USDC and funds the lenders
 * and the buyer. Idempotent: accounts already in `.env.accounts` are reused, and association and
 * funding are skipped when the mirror node shows them done.
 *
 *   pnpm -r build && pnpm tsx scripts/setup-accounts.ts
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  associateUsdc,
  createEcdsaAccount,
  hieroClient,
  mirror,
  pickUsdcSource,
  transferUsdc,
} from "@casheth/hedera";
import { DEMO_ACCOUNTS, hashscan, loadEnv, type DemoAccount } from "@casheth/shared";

const INITIAL_HBAR = 20;
const MIN_HBAR_TINYBARS = 19n * 100_000_000n;

interface Funding {
  units: bigint;
  source: "operator" | "merchant";
}

/** USDC targets in 6-decimal units, and which funded account pays them. */
const USDC_FUNDING: Partial<Record<DemoAccount, Funding>> = {
  LENDER_A: { units: 4_000_000n, source: "operator" },
  LENDER_B: { units: 2_000_000n, source: "operator" },
  LENDER_C: { units: 1_000_000n, source: "operator" },
  BUYER: { units: 10_000_000n, source: "merchant" },
};

interface DemoRecord {
  id: string;
  key: string;
  evm: string;
}

const ENV_ACCOUNTS_PATH = fileURLToPath(new URL("../.env.accounts", import.meta.url));

/** WORKER_RESEARCH -> workerResearch */
const label = (prefix: DemoAccount): string =>
  prefix.toLowerCase().replace(/_([a-z])/g, (_, c: string) => c.toUpperCase());

const env = loadEnv();
const usdc = env.USDC_TOKEN_ID;
const client = hieroClient(env);
const records = new Map<DemoAccount, DemoRecord>();

function saveEnvAccounts(): void {
  const lines = ["# Generated by scripts/setup-accounts.ts. Testnet demo accounts; never commit."];
  for (const [prefix, r] of records) {
    lines.push(`${prefix}_ID=${r.id}`, `${prefix}_KEY=${r.key}`, `${prefix}_EVM=${r.evm}`);
  }
  writeFileSync(ENV_ACCOUNTS_PATH, `${lines.join("\n")}\n`, { mode: 0o600 });
}

// 1. Accounts. Saved after each creation so a crash never loses a key.
for (const prefix of DEMO_ACCOUNTS) {
  const id = env[`${prefix}_ID`];
  const key = env[`${prefix}_KEY`];
  const evm = env[`${prefix}_EVM`];
  if (id) {
    if (!key || !evm) {
      throw new Error(`${prefix}_ID is set but ${prefix}_KEY or ${prefix}_EVM is missing`);
    }
    records.set(prefix, { id, key, evm });
    console.log(`${label(prefix)}: exists ${id}`);
    continue;
  }
  const created = await createEcdsaAccount(client, {
    initialHbar: INITIAL_HBAR,
    label: label(prefix),
  });
  records.set(prefix, { id: created.accountId, key: created.privateKey, evm: created.evmAddress });
  saveEnvAccounts();
  console.log(`${label(prefix)}: created ${created.accountId} ${hashscan.tx(created.txId)}`);
}
saveEnvAccounts();

// 2. USDC association (explicit, even though auto-association slots exist).
for (const [prefix, r] of records) {
  const account = await mirror.waitFor(() => mirror.account(env, r.id));
  if (account.balance.tokens.some((t) => t.token_id === usdc)) {
    console.log(`${label(prefix)}: USDC already associated`);
    continue;
  }
  const txId = await associateUsdc(client, r.id, r.key, usdc);
  console.log(`${label(prefix)}: associated USDC ${hashscan.tx(txId)}`);
}

// 3. USDC funding, topped up to the target. The source is chosen at run time: the configured one
// if it holds enough, otherwise the operator (e.g. after sweep-usdc.ts emptied the merchant).
const sources = {
  operator: { name: "operator", id: env.HEDERA_OPERATOR_ID, key: env.HEDERA_OPERATOR_KEY },
  merchant: { name: "merchant", id: env.MERCHANT_ACCOUNT_ID, key: env.MERCHANT_KEY },
};
const sourceWithBalance = async (s: { name: string; id: string; key: string }) => ({
  ...s,
  balance: await mirror.tokenBalance(env, s.id, usdc),
});
for (const [prefix, funding] of Object.entries(USDC_FUNDING) as [DemoAccount, Funding][]) {
  const r = records.get(prefix)!;
  const balance = await mirror.tokenBalance(env, r.id, usdc);
  if (balance >= funding.units) {
    console.log(`${label(prefix)}: already holds ${balance} USDC units`);
    continue;
  }
  const needed = funding.units - balance;
  const source = pickUsdcSource(
    needed,
    await sourceWithBalance(sources[funding.source]),
    await sourceWithBalance(sources.operator),
  );
  const txId = await transferUsdc(client, {
    tokenId: usdc,
    from: source.id,
    fromKey: source.key,
    to: r.id,
    units: needed,
  });
  console.log(`${label(prefix)}: funded ${needed} USDC units from ${source.name} ${hashscan.tx(txId)}`);
  // Let the mirror node catch up so the next source-balance read is not stale.
  await mirror.waitFor(async () => (await mirror.tokenBalance(env, r.id, usdc)) >= funding.units, {
    attempts: 15,
    delayMs: 2000,
  });
}

// 4. Verify on the mirror node (lags consensus by a few seconds).
console.log("\nlabel | account | HBAR | USDC units");
const evidenceRows: string[] = [];
for (const [prefix, r] of records) {
  const wantUsdc = USDC_FUNDING[prefix]?.units ?? 0n;
  const account = await mirror.waitFor(
    async () => {
      const a = await mirror.account(env, r.id);
      const tokens = BigInt(a.balance.tokens.find((t) => t.token_id === usdc)?.balance ?? 0);
      return BigInt(a.balance.balance) >= MIN_HBAR_TINYBARS && tokens >= wantUsdc ? a : undefined;
    },
    { attempts: 15, delayMs: 2000 },
  );
  const hbar = Number(account.balance.balance) / 1e8;
  const units = account.balance.tokens.find((t) => t.token_id === usdc)?.balance ?? 0;
  console.log(`${label(prefix)} | ${r.id} | ${hbar} | ${units}`);
  evidenceRows.push(`| ${label(prefix)} | [${r.id}](${hashscan.account(r.id)}) | \`${r.evm}\` |`);
}
console.log("\nEVIDENCE.md Accounts rows:\n| Label | Account | EVM address |\n| --- | --- | --- |");
console.log(evidenceRows.join("\n"));
client.close();
